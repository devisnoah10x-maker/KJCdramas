export const shortBySlug = (slug: string) =>
  shorts.find((s) => s.slug === slug);

export const shortsForDrama = (dramaSlug: string) =>
  shorts.filter((s) => s.relatedDrama === dramaSlug);

export const relatedShorts = (currentShort: Short, limit = 6) => {
  const sameDrama = shorts.filter(
    (s) =>
      s.id !== currentShort.id &&
      s.relatedDrama === currentShort.relatedDrama
  );

  const sameCountryGenre = shorts.filter(
    (s) =>
      s.id !== currentShort.id &&
      s.relatedDrama !== currentShort.relatedDrama &&
      s.country === currentShort.country &&
      s.genre === currentShort.genre
  );

  const sameCountry = shorts.filter(
    (s) =>
      s.id !== currentShort.id &&
      s.relatedDrama !== currentShort.relatedDrama &&
      s.country === currentShort.country
  );

  const others = shorts.filter(
    (s) =>
      s.id !== currentShort.id &&
      s.relatedDrama !== currentShort.relatedDrama &&
      s.country !== currentShort.country
  );

  return [
    ...sameDrama,
    ...sameCountryGenre,
    ...sameCountry,
    ...others
  ].slice(0, limit);
};