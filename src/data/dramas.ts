export const dramaBySlug = (slug: string) => dramas.find((d) => d.slug === slug);
export const publishedDramas = dramas.filter((d) => d.state === 'published');
export const byCountry = (code: string) => publishedDramas.filter((d) => d.country === code);
export const trendingDramas = publishedDramas.filter((d) => d.trending);
export const featuredDramas = dramas.filter((d) => d.featured);
export const movies = publishedDramas.filter((d) => d.type === 'movie');
export const seriesOnly = publishedDramas.filter((d) => d.type === 'drama');
export const latestDramas = [...publishedDramas].sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
export const mostViewed = [...publishedDramas].sort((a, b) => b.views - a.views);
export const byGenre = (genreName: string) =>
publishedDramas.filter((d) => d.genres.some((g) => g.toLowerCase() === genreName.toLowerCase()));
export const relatedTo = (drama: Drama, limit = 6) =>
publishedDramas.
filter((d) => d.id !== drama.id).
map((d) => ({
  drama: d,
  score:
  d.genres.filter((g) => drama.genres.includes(g)).length * 2 + (d.country === drama.country ? 1 : 0)
})).
sort((a, b) => b.score - a.score).
slice(0, limit).
map((x) => x.drama);